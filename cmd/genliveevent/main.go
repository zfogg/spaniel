// genliveevent derives the browser union and runtime validator from Go's wire
// registry. HTTP rows reference the existing OpenAPI-derived browser DTOs.
package main

import (
	"encoding/json"
	"fmt"
	"github.com/zfogg/spaniel/internal/liveevent"
	"os"
	"reflect"
	"sort"
	"strings"
)

func main() {
	var b strings.Builder
	b.WriteString("// Code generated by genliveevent; DO NOT EDIT.\n")
	keys := make([]string, 0, len(liveevent.Payloads))
	for k := range liveevent.Payloads {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	types := map[string]reflect.Type{"MetricRowPayload": reflect.TypeFor[liveevent.MetricRowPayload]()}
	var collect func(reflect.Type)
	collect = func(t reflect.Type) {
		if t == nil {
			return
		}
		if t.Kind() == reflect.Pointer || t.Kind() == reflect.Slice {
			collect(t.Elem())
			return
		}
		if t.Kind() != reflect.Struct || types[t.Name()] != nil {
			return
		}
		types[t.Name()] = t
		for i := 0; i < t.NumField(); i++ {
			collect(t.Field(i).Type)
		}
	}
	for _, k := range keys {
		collect(liveevent.Payloads[k])
	}
	names := make([]string, 0, len(types))
	for n := range types {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		t := types[n]
		switch n {
		case "SelfTracePayload":
			b.WriteString("export type SelfTracePayload = import('../lib/api').TraceRow\n")
			continue
		case "SelfSpanPayload":
			b.WriteString("export type SelfSpanPayload = import('../lib/api').SpanRow\n")
			continue
		case "SelfLogPayload":
			b.WriteString("export type SelfLogPayload = import('../lib/api').Log\n")
			continue
		}
		fmt.Fprintf(&b, "export interface %s {\n", n)
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			tag := strings.Split(f.Tag.Get("json"), ",")
			optional := ""
			if strings.Contains(f.Tag.Get("json"), "omitempty") {
				optional = "?"
			}
			typ := tsType(f.Type)
			switch n + "." + f.Name {
			case "MetricPayload.Row":
				typ = "MetricRowPayload"
			case "LiveStatePayload.Stats":
				typ = "import('../lib/api').Stats"
			case "LiveStatePayload.Sources":
				typ = "import('../lib/api').SourceStats[]"
			case "AlertSyncPayload.Events":
				typ = "import('../lib/api').AlertEvent[]"
			}
			fmt.Fprintf(&b, "%s%s: %s\n", tag[0], optional, typ)
		}
		b.WriteString("}\n")
	}
	b.WriteString("export type WsEvent =\n")
	for i, k := range keys {
		sep := " | "
		if i == 0 {
			sep = " "
		}
		fmt.Fprintf(&b, "%s{type: %q; timestamp_ns: number", sep, k)
		if t := liveevent.Payloads[k]; t != nil {
			fmt.Fprintf(&b, "; payload: %s", t.Name())
		}
		b.WriteString("}\n")
	}
	schemas := map[string]any{}
	for _, k := range keys {
		schemas[k] = shape(liveevent.Payloads[k])
	}
	j, _ := json.Marshal(schemas)
	fmt.Fprintf(&b, "const shapes: Record<string, Shape | null> = %s\n", j)
	j, _ = json.Marshal(liveevent.Invalidations)
	fmt.Fprintf(&b, "export const invalidations: Record<string, string[]> = %s\n", j)
	j, _ = json.Marshal(liveevent.ResourceAliases)
	fmt.Fprintf(&b, "const resourceAliases: Record<string,string[]> = %s\n", j)
	j, _ = json.Marshal(liveevent.TelemetryResources)
	fmt.Fprintf(&b, "export const telemetryResources: string[] = %s\n", j)
	b.WriteString(`
type Shape = {kind: string; fields?: Record<string, Shape>; element?: Shape}
function valid(value: unknown, shape: Shape): boolean {
 if (shape.kind === 'any' || value === null) return true
 if (shape.kind === 'array') return Array.isArray(value) && value.every(v => valid(v, shape.element!))
 if (shape.kind !== 'object') return typeof value === shape.kind
 if (typeof value !== 'object' || Array.isArray(value)) return false
 return Object.entries(value as Record<string,unknown>).every(([k,v]) => !shape.fields?.[k] || valid(v,shape.fields[k]))
}
export function decodeEvent(value: unknown): WsEvent | null {
 if (!value || typeof value !== 'object') return null
 const event = value as Record<string,unknown>
 if (typeof event.type !== 'string' || !(event.type in shapes) || typeof event.timestamp_ns !== 'number') return null
 const shape = shapes[event.type]
 if (shape && (!event.payload || !valid(event.payload,shape))) return null
 return value as WsEvent
}
function rawChangedResources(event: WsEvent): string[] {
 if (event.type === 'metric' && event.payload.catalogOnly) return []
 if (event.type === 'resources_changed') return event.payload.resources
 if (event.type === 'definition_sync') {
   if (event.payload.status !== 'updated') return []
   return event.payload.kind === 'dashboard' ? ['dashboards','dashboard-panel'] : event.payload.kind === 'alert' ? ['alerts'] : []
 }
 return invalidations[event.type] ?? []
}
export function changedResources(event: WsEvent): string[] {
 return rawChangedResources(event).flatMap(resource => [resource,...(resourceAliases[resource] ?? [])])
}
`)
	if err := os.WriteFile("frontend/src/generated/liveevent.ts", []byte(b.String()), 0644); err != nil {
		panic(err)
	}
}
func tsType(t reflect.Type) string {
	switch t.Kind() {
	case reflect.Pointer:
		return tsType(t.Elem())
	case reflect.Interface:
		return "unknown"
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Slice:
		return tsType(t.Elem()) + "[]"
	case reflect.Map:
		return "Record<string, " + tsType(t.Elem()) + ">"
	case reflect.Struct:
		return t.Name()
	default:
		return "number"
	}
}
func shape(t reflect.Type) any {
	if t == nil {
		return nil
	}
	if t.Kind() == reflect.Pointer {
		return shape(t.Elem())
	}
	switch t.Kind() {
	case reflect.Interface:
		return map[string]any{"kind": "any"}
	case reflect.Slice:
		return map[string]any{"kind": "array", "element": shape(t.Elem())}
	case reflect.Struct:
		fields := map[string]any{}
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			fields[strings.Split(f.Tag.Get("json"), ",")[0]] = shape(f.Type)
		}
		return map[string]any{"kind": "object", "fields": fields}
	case reflect.Map:
		return map[string]any{"kind": "object"}
	case reflect.String:
		return map[string]any{"kind": "string"}
	case reflect.Bool:
		return map[string]any{"kind": "boolean"}
	default:
		return map[string]any{"kind": "number"}
	}
}
